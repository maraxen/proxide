/// Full-protein parity test: place rot_index=0 default-bin CB onto all 30 non-GLY residues of
/// 2ZTA chain A (GCN4 leucine zipper), compute the 30×30 CB-CB distance matrix, and assert it
/// matches the Python-derived reference within 1e-6 Å.
///
/// 2ZTA covers 14 unique amino acids and real helical backbone geometry, exercising the frame
/// transform pipeline across a full protein. GLY (residue 31) is skipped — its na=0 handling
/// is verified separately in test_distogram_with_gly_and_pro.
///
/// Cross-check: the upper-left 7×7 block of this matrix matches REF_DISTOGRAM exactly, since
/// 2ZTA residues 1-7 (ARG MET LYS GLN LEU GLU ASP) are the same structure used in small.pdb.
#[test]
fn test_distogram_2zta_chain_a() {
    let lib = RotamerLibrary::load(&real_rotlib_path()).unwrap();

    let pdb_path = real_pdb_path_2zta();
    if !pdb_path.exists() {
        eprintln!("Skipping test: 2ZTA.pdb not found at {:?}", pdb_path);
        return;
    }

    let all_residues = parse_pdb_backbone(&pdb_path);
    let chain_a: Vec<_> = all_residues.iter().filter(|r| r.chain == 'A').collect();
    assert_eq!(
        chain_a.len(),
        31,
        "expected 31 chain-A residues with full backbone in 2ZTA"
    );

    // GLY at position 31 has no sidechain; filter it for the CB distogram.
    let non_gly: Vec<_> = chain_a.iter().filter(|r| r.aa != "GLY").collect();
    assert_eq!(
        non_gly.len(),
        30,
        "expected 30 non-GLY residues in 2ZTA chain A"
    );

    // Place CB for each non-GLY residue (rot_index=0, sentinel phi/psi → default bin).
    let cb_positions: Vec<[f64; 3]> = non_gly
        .iter()
        .map(|res| {
            let placed = lib
                .place_rotamer(&res.aa, 9999.0, 9999.0, 0, false, res.n, res.ca, res.c)
                .unwrap_or_else(|e| {
                    panic!("A{}/{}: place_rotamer failed: {e}", res.res_seq, res.aa)
                });
            placed
                .atoms
                .iter()
                .find(|a| a.name == "CB")
                .unwrap_or_else(|| panic!("A{}/{}: no CB atom", res.res_seq, res.aa))
                .xyz
        })
        .collect();

    let n = non_gly.len();
    for i in 0..n {
        for j in 0..n {
            let got = dist(cb_positions[i], cb_positions[j]);
            let ref_val = REF_DISTOGRAM_2ZTA_A[i * n + j];
            assert!(
                (got - ref_val).abs() < TOL,
                "distogram[{i},{j}] (A{}/{} vs A{}/{}): expected {ref_val:.9}, got {got:.9}, diff {:.2e}",
                non_gly[i].res_seq, non_gly[i].aa,
                non_gly[j].res_seq, non_gly[j].aa,
                (got - ref_val).abs()
            );
        }
    }
}
