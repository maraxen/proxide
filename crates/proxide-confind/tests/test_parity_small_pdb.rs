#[test]
fn test_seq_const_contacts_small_pdb() {
    let (rlib, bb) = match load_or_skip() {
        Some(v) => v,
        None => return,
    };

    let cf = ConFind::new(rlib, bb.clone(), false);

    // Phase A: cache all residues (required before contact_degree_with_clashes)
    for ri in all_res(&cf) {
        cf.cache_residue(ri).expect("cache_residue should succeed");
    }

    // Build lookup: (chain_id, res_id) -> ResidueIndex
    let id_to_ri: HashMap<(String, i32), proxide_confind::ResidueIndex> = all_res(&cf)
        .iter()
        .map(|&ri| {
            let id = cf.residue_id(ri);
            ((id.chain_id.clone(), id.res_id), ri)
        })
        .collect();

    for &(ca, ra, cb, rb, constrained_aa, expected_cd) in REF_SEQ_CONST {
        let ri_a = *id_to_ri
            .get(&(ca.to_string(), ra))
            .unwrap_or_else(|| panic!("residue {},{} not found", ca, ra));
        let ri_b = *id_to_ri
            .get(&(cb.to_string(), rb))
            .unwrap_or_else(|| panic!("residue {},{} not found", cb, rb));
        let (actual_cd, _) = cf
            .contact_degree_with_clashes(ri_a, ri_b, Some(&[constrained_aa]), None)
            .unwrap_or_else(|e| {
                panic!(
                    "contact_degree_with_clashes {},{}->{},{}/{}: {:?}",
                    ca, ra, cb, rb, constrained_aa, e
                )
            });
        assert!(
            (actual_cd - expected_cd).abs() < TOLERANCE,
            "seq_const {},{}->{},{}/{}: got {:.6}, expected {:.6} (diff {:.2e})",
            ca,
            ra,
            cb,
            rb,
            constrained_aa,
            actual_cd,
            expected_cd,
            (actual_cd - expected_cd).abs()
        );
    }
}
