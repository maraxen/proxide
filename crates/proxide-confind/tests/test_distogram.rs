/// Full-protein CB distogram parity test: place rot_index=0 default-bin CB onto all 111
/// non-GLY non-PRO residues of 1DC7 chain A, compute the 111×111 CB-CB distance matrix,
/// and assert it matches the Python-derived reference within 1e-6 Å.
///
/// GLY and PRO are excluded, matching Mosaist ConFind's aaNames convention
/// ("all but GLY and PRO", mstcondeg.cpp:62). 1DC7 contains all 20 standard amino acids
/// across 124 residues in chain A; excluding the 7 GLY and 6 PRO leaves 111 residues
/// spanning 18 amino acid types.
#[test]
#[ignore = "requires rotamer library and 1DC7 — set ROTLIB_PATH and DC7_PDB_PATH env vars to run"]
fn test_distogram_1dc7_chain_a() {
    let lib_path = real_rotlib_path();
    if !lib_path.exists() {
        eprintln!("Skipping: rotlib.bin not found at {:?}", lib_path);
        return;
    }
    let lib = RotamerLibrary::load(&lib_path)
        .unwrap_or_else(|e| panic!("Failed to load rotamer library: {e}"));

    let backbone = match load_1dc7_backbone() {
        Some(bb) => bb,
        None => {
            eprintln!("Skipping: 1DC7.pdb not found");
            return;
        }
    };

    // Collect non-GLY non-PRO chain A residues with complete N/CA/C backbone.
    let non_gly_pro: Vec<_> = backbone
        .bb
        .iter()
        .zip(backbone.ids.iter())
        .filter(|(res, id)| {
            id.chain_id == "A"
                && res.res_name != "GLY"
                && res.res_name != "PRO"
                && res.n.is_some()
                && res.ca.is_some()
                && res.c.is_some()
        })
        .collect();

    assert_eq!(
        non_gly_pro.len(),
        111,
        "expected 111 non-GLY non-PRO chain A residues in 1DC7; got {}",
        non_gly_pro.len()
    );

    let cb_positions: Vec<[f64; 3]> = non_gly_pro
        .iter()
        .map(|(res, id)| {
            let n = res.n.unwrap();
            let ca = res.ca.unwrap();
            let c = res.c.unwrap();
            let placed = lib
                .place_rotamer(&res.res_name, 9999.0, 9999.0, 0, false, n, ca, c)
                .unwrap_or_else(|e| {
                    panic!("A{}/{}: place_rotamer failed: {e}", id.res_id, res.res_name)
                });
            placed
                .atoms
                .iter()
                .find(|a| a.name == "CB")
                .unwrap_or_else(|| panic!("A{}/{}: no CB atom", id.res_id, res.res_name))
                .xyz
        })
        .collect();

    let n = non_gly_pro.len();
    for i in 0..n {
        for j in 0..n {
            let got = dist(cb_positions[i], cb_positions[j]);
            let ref_val = REF_DISTOGRAM_1DC7_A[i * n + j];
            assert!(
                (got - ref_val).abs() < TOL,
                "distogram[{i},{j}] (A{}/{} vs A{}/{}): expected {ref_val:.9}, got {got:.9}, diff {:.2e}",
                non_gly_pro[i].1.res_id,
                non_gly_pro[i].0.res_name,
                non_gly_pro[j].1.res_id,
                non_gly_pro[j].0.res_name,
                (got - ref_val).abs()
            );
        }
    }
}
